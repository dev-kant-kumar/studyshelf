export function getCoursePyqs(courseId) {
  if (!courseId) return pyqPapers
  const normalized = courseId.toLowerCase()
  return pyqPapers.filter(paper => paper.courseId === normalized)
}

export function getPaperPyqs(courseId, semesterId, paperId) {
  return pyqPapers.filter(
    paper =>
      paper.courseId === courseId?.toLowerCase() &&
      (!semesterId || paper.semesterId === semesterId) &&
      (!paperId || paper.paperId === paperId)
  )
}
