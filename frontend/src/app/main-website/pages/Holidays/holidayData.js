export function getIndiaToday(date = new Date()) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata' }).format(date)
}

export function getHolidayStatus(holiday, todayStr) {
  const current = todayStr || getIndiaToday()
  if (current >= holiday.startDate && current <= holiday.endDate) {
    return 'active'
  }
  if (current < holiday.startDate) {
    return 'upcoming'
  }
  return 'past'
}

export function getNextUpcomingHoliday(todayStr) {
  const current = todayStr || getIndiaToday()
  const active = holidays2026.find(h => current >= h.startDate && current <= h.endDate)
  if (active) return { holiday: active, status: 'active' }

  const upcoming = holidays2026.find(h => current < h.startDate)
  return upcoming ? { holiday: upcoming, status: 'upcoming' } : null
}
